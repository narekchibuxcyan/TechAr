async function seedFirmwareAndOtaJob() {
  let firmware = await prisma.firmware.findUnique({
    where: { model_version: { model: "ESP32-ENV-V1", version: "1.1.0" } },
  });

  if (!firmware) {
    // Reuses the same validated storage path a real admin upload goes
    // through (server/src/services/firmware.service.ts), so this fixture
    // can't drift from what the real upload/OTA flow actually accepts.
    const mockBinary = crypto.randomBytes(8192);
    const stored = await storeFirmwareFile("seed-mock-firmware-v1.1.0.bin", mockBinary);
    firmware = await prisma.firmware.create({
      data: {
        version: "1.1.0",
        model: "ESP32-ENV-V1",
        filePath: stored.filePath,
        checksumSha256: stored.checksumSha256,
        fileSizeBytes: stored.fileSizeBytes,
        uploadedById: ADMIN_ID,
      },
    });
  }

  // Ready for the simulator to discover immediately: run it pointed at
  // DEVICE_1 (Living Room Sensor, the default config) and it will find,
  // download, and "flash" this job on its first OTA poll.
  await prisma.firmwareUpdateJob.create({
    data: { firmwareId: firmware.id, deviceId: DEVICE_1_ID, status: "SCHEDULED", createdById: ADMIN_ID },
  });
}

