async function seedUsers() {
  const adminPasswordHash = await hashPassword(ADMIN_PASSWORD);
  await prisma.user.upsert({
    where: { id: ADMIN_ID },
    update: {},
    create: {
      id: ADMIN_ID,
      email: "admin@iot-platform.local",
      passwordHash: adminPasswordHash,
      fullName: "Platform Admin",
      role: "ADMIN",
      status: "ACTIVE",
    },
  });

  const testPasswordHash = await hashPassword(TEST_USER_PASSWORD);

  await prisma.user.upsert({
    where: { id: ALICE_ID },
    update: {},
    create: {
      id: ALICE_ID,
      email: "alice@example.com",
      passwordHash: testPasswordHash,
      fullName: "Alice Example",
      role: "USER",
      status: "PENDING",
    },
  });

  await prisma.user.upsert({
    where: { id: BOB_ID },
    update: {},
    create: {
      id: BOB_ID,
      email: "bob@example.com",
      passwordHash: testPasswordHash,
      fullName: "Bob Example",
      role: "USER",
      status: "PENDING",
    },
  });

  await prisma.user.upsert({
    where: { id: CAROL_ID },
    update: {},
    create: {
      id: CAROL_ID,
      email: "carol@example.com",
      passwordHash: testPasswordHash,
      fullName: "Carol Example",
      role: "USER",
      status: "ACTIVE",
    },
  });

  // Predefined OTP codes so POST /api/auth/verify-otp can be exercised
  // end-to-end without a real inbox. A far-future expiry keeps them usable
  // for the life of a local dev session — the real issueOtp() flow uses a
  // strict 10-minute TTL; this is a test fixture, not the production path.
  const farFuture = new Date(Date.now() + 365 * 24 * 60 * 60 * 1000);
  await prisma.otpCode.deleteMany({
    where: { userId: { in: [ALICE_ID, BOB_ID] }, purpose: "REGISTRATION" },
  });
  await prisma.otpCode.createMany({
    data: [
      { userId: ALICE_ID, purpose: "REGISTRATION", codeHash: sha256Hex("111111"), expiresAt: farFuture },
      { userId: BOB_ID, purpose: "REGISTRATION", codeHash: sha256Hex("222222"), expiresAt: farFuture },
    ],
  });
}

async function seedDevices() {
  for (const d of DEVICE_SEEDS) {
    const shared = {
      serialNumber: d.serialNumber,
      name: d.name,
      model: d.model,
      hardwareRevision: d.hardwareRevision,
      ownerId: d.ownerId,
      status: d.status,
      firmwareVersion: d.firmwareVersion,
      apiKeyHash: sha256Hex(d.apiKey),
      lastSeenAt: d.status === "ONLINE" ? new Date() : null,
    };

    await prisma.device.upsert({
      where: { id: d.id },
      update: shared,
      create: { id: d.id, createdByAdminId: ADMIN_ID, ...shared },
    });
  }
}

async function resetHistoricalData() {
  const deviceIds = DEVICE_SEEDS.map((d) => d.id);
  await prisma.deviceTelemetry.deleteMany({ where: { deviceId: { in: deviceIds } } });
  await prisma.deviceConnectionLog.deleteMany({ where: { deviceId: { in: deviceIds } } });
  await prisma.firmwareUpdateJob.deleteMany({ where: { deviceId: { in: deviceIds } } });
  await prisma.orderStatusHistory.deleteMany({ where: { orderId: { in: [ORDER_1_ID, ORDER_2_ID] } } });
  await prisma.orderItem.deleteMany({ where: { orderId: { in: [ORDER_1_ID, ORDER_2_ID] } } });
  await prisma.order.deleteMany({ where: { id: { in: [ORDER_1_ID, ORDER_2_ID] } } });
}

function hoursAgo(h: number): Date {
  return new Date(Date.now() - h * 60 * 60 * 1000);
}

async function seedTelemetryAndLogs() {
  const telemetryRows: { deviceId: string; metric: string; value: number; unit: string; recordedAt: Date }[] = [];

  for (const d of DEVICE_SEEDS) {
    for (let i = 12; i >= 0; i--) {
      const recordedAt = hoursAgo(i);
      telemetryRows.push(
        {
          deviceId: d.id,
          metric: "temperature",
          value: Number((20 + Math.sin(i / 2) * 3 + Math.random()).toFixed(1)),
          unit: "°C",
          recordedAt,
        },
        {
          deviceId: d.id,
          metric: "humidity",
          value: Number((45 + Math.cos(i / 3) * 8 + Math.random() * 2).toFixed(1)),
          unit: "%",
          recordedAt,
        },
        {
          deviceId: d.id,
          metric: "batteryLevel",
          value: Number(Math.max(15, 100 - i * 1.5).toFixed(0)),
          unit: "%",
          recordedAt,
        },
      );
    }
  }
  await prisma.deviceTelemetry.createMany({ data: telemetryRows });

  const connectionLogRows: {
    deviceId: string;
    event: "CONNECTED" | "DISCONNECTED" | "FORCED_STATE_CHANGE";
    ipAddress: string;
    detail: string | null;
    occurredAt: Date;
  }[] = [];

  DEVICE_SEEDS.forEach((d, index) => {
    const ip = `10.0.0.${10 + index}`;
    for (let i = 8; i >= 1; i--) {
      connectionLogRows.push({
        deviceId: d.id,
        event: i % 2 === 0 ? "DISCONNECTED" : "CONNECTED",
        ipAddress: ip,
        detail: null,
        occurredAt: hoursAgo(i * 2),
      });
    }
    // End on an event consistent with the device's current seeded status.
    connectionLogRows.push({
      deviceId: d.id,
      event: d.status === "ONLINE" ? "CONNECTED" : "DISCONNECTED",
      ipAddress: ip,
      detail: null,
      occurredAt: hoursAgo(0.5),
    });
  });

  connectionLogRows.push({
    deviceId: DEVICE_5_ID,
    event: "FORCED_STATE_CHANGE",
    ipAddress: "10.0.0.14",
    detail: "Admin forced state ONLINE -> DISABLED. Reason: Awaiting customer assignment.",
    occurredAt: hoursAgo(1),
  });

  await prisma.deviceConnectionLog.createMany({ data: connectionLogRows });
}

